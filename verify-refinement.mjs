import assert from 'node:assert/strict';
import {parseFx,fxSnapshot} from './app/fx-data.ts';
import {macroEvents,selectMacroEvents} from './app/macro-data.ts';
const xml=`<Cube><Cube time='2026-09-09'>${Object.entries(fxSnapshot.rates).map(([currency,rate])=>`<Cube currency='${currency}' rate='${rate}'/>`).join('')}</Cube></Cube>`;
assert.deepEqual(parseFx(xml),{...fxSnapshot,mode:'official'});
assert.deepEqual(parseFx(xml.replaceAll("'",'"')).rates,fxSnapshot.rates);
assert.throws(()=>parseFx(xml.replace('1.1652','0')));assert.throws(()=>parseFx(xml.replace("currency='GBP'","currency='ZZZ'")));assert.throws(()=>parseFx(xml.replace('2026-09-09','2026-02-30')));
assert.ok(macroEvents.every(e=>['NL','US'].includes(e.country)&&Number.isFinite(Date.parse(e.at))));
assert.equal(new Set(macroEvents.map(e=>e.id)).size,macroEvents.length);
assert.ok(selectMacroEvents({country:'NL'}).every(e=>e.country==='NL'));
assert.deepEqual(selectMacroEvents({country:'US',topic:'Inflatie',from:'2026-10-01',until:'2026-10-14'}).map(e=>e.title),['Consumentenprijzen (CPI)']);
assert.equal(selectMacroEvents({from:'2030-01-01'}).length,0);
assert.equal(selectMacroEvents({from:'2026-11-01',until:'2026-10-01'}).length,0);
const octoberCost=macroEvents.find(e=>e.title.startsWith('Loonkosten'));
assert.equal(new Intl.DateTimeFormat('nl-NL',{hour:'2-digit',minute:'2-digit',timeZone:'Europe/Amsterdam'}).format(new Date(octoberCost.at)),'13:30');
console.log('ECB parser and macro country/topic/date filters, unique events and timezones passed.');
